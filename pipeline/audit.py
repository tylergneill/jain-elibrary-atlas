"""Audit stage: what the two catalogues get wrong, published for a reader.

An independent index is the only place a source's own mistakes become visible.
This finds them, describes them specifically enough to act on, and regenerates
a section of `docs/about.html` between the AUDIT markers, plus every
`data-stat` figure in the hand-written prose.

Modelled on `../sanskrit-documents-atlas/pipeline/audit.py` (itself after the
e-bharatisampat and wikisource siblings); the conventions and the markup are
lifted deliberately so the pages read as one project. None of their checks
transfer.

## Standing rules

**It never mutates anything** but its own region of `about.html` and the
tagged figures. A finding is for a human to look at, never an auto-correction.

**Every published number is re-derived by the run that publishes it.** Until
2026-10-17 this page computed its figures in the browser from `tree.json`; that
kept them current, but left a page that read wrong with JS off and an audit
nobody could run from a terminal.

**The subject is the Sanskrit tier.** The tree also carries the Prakrit tier
(`prakrit: true`); the prose and the findings leave it out, apart from the few
figures that describe it by name.

## Entirely offline

Reads `docs/data/tree.json`, `docs/data/changelog.json`, and Quantum's text
journal and sizes (`data/text_fetch_log.jsonl`, `data/sizes.jsonl`) for the
booktexts that came back empty -- the tree records only which text the Atlas
uses, not that Quantum's was blank. `build_tree.empty_booktexts` is the one
definition of blank, so the tree and this list cannot disagree. No network, no rivulet, no login.

## The checks

Upstream -- something jainelibrary.org or Jain Quantum could fix -- except 5:

1. **Publication years that cannot be right.**
2. **Quantum booktexts that are empty** -- the page exists, with page markers,
   and nothing on it (or only a byte-order mark); the library's own OCR of the
   same book has text.
3. **Quantum lists the book but shows no text, though the library has OCR'd
   it** -- the library's file is behind its login, Quantum's text stopped in
   mid-2020, and nobody carried the one into the other.
4. **Online before the library's OCR batch, but not OCR'd by it.**
5. **Texts that hold nothing** -- a text the tree counts that measures zero
   bytes. Ours, not upstream: `empty_booktexts` should keep it at none found,
   and it prints to the console only.
6. **Language strings that repeat themselves.**
7. **Classification strings with empty slots.**
8. **Items in only one of the two catalogues** -- the same library under the
   same serials, but neither lists all of it. A book only Quantum lists has no
   accession date (the date is the library's) and no OCR file (the file is the
   library's), so where Quantum has no text it has none anywhere.

    make audit                # the checks, to the console
    make audit-update-about   # and rewrite the About region and figures
"""

import argparse
import collections
import html
import json
import re
from datetime import date

from pipeline.build_tree import NOT_CANON, empty_booktexts, load_sizes
from pipeline.config import (CHANGELOG_PATH, DOCS_DIR, OCR_SIZES_PATH, SIZES_PATH,
                             TEXT_LOG_PATH, TREE_PATH)

SITE_ROOT = "https://jainqq.org"

ABOUT_HTML_PATH = DOCS_DIR / "about.html"

AUDIT_START_MARKER = (
    "<!-- AUDIT:START -- generated by `python -m pipeline.audit --update-about`; "
    "do not hand-edit between these markers -->"
)
AUDIT_END_MARKER = "<!-- AUDIT:END -->"

# A finding is meant to be actionable, not exhaustive.
MAX_EXAMPLES = 60

# The figures `all_stats` already publishes that the prose quotes. Named rather
# than spread: the tag contract is strict both ways, and a new all_stats key
# must not demand a tag the page has no sentence for.
FROM_ALL_STATS = ("count", "sized", "canon_count", "quantum_text_count",
                  "elibrary_text_count", "transliterated_bytes", "library_count",
                  "library_text_count", "sanskrit_prakrit_count", "any_sanskrit_count")


# --- loading ----------------------------------------------------------------


def load_tree(path=TREE_PATH):
    return json.loads(path.read_text(encoding="utf-8"))


def load_changelog(path=CHANGELOG_PATH):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def sanskrit_works(tree):
    return [w for w in tree.get("works", []) if not w.get("prakrit")]


def in_quantum(w):
    return "quantum" in (w.get("sources") or [])


def in_api(w):
    return "api" in (w.get("sources") or [])


def bytes_of(w):
    return (w.get("sizes") or {}).get("transliterated_bytes") or 0


def newest(works, field="added"):
    return max((w[field] for w in works if w.get(field)), default="")


def batch_date(works):
    """The day the library's OCR files say they were made. One batch, so far."""
    return min((w["ocr_created"] for w in works if w.get("ocr_created")), default=None)


# --- checks -----------------------------------------------------------------


def odd_year(w):
    """Not a four-digit year between printed Jain literature and the present."""
    if not w.get("publish_year"):
        return False
    y = str(w["publish_year"])[:4]
    return not y.isdigit() or not 1700 <= int(y) <= date.today().year


def has_empty_slot(w):
    """`Book_Devnagari, , , agam_index`: nothing between two commas, or after the last."""
    return any(not t.strip() for t in (w.get("classification") or "").split(","))


def repeats_language(w):
    """`Sanskrit, Sanskrit`: the tier admits a string whose tokens are all Sanskrit."""
    return "," in (w.get("language") or "")


def by_serial(works):
    return sorted(works, key=lambda w: w["id"])


def by_year(works):
    counts = collections.Counter((w.get("added") or "")[:4] or "undated" for w in works)
    return sorted(counts.items())


def find_odd_years(works):
    return by_serial(w for w in works if odd_year(w))


def find_empty_booktexts(works, empty):
    return by_serial(w for w in works if w["id"] in empty)


def find_unpublished_ocr(works, library_blank):
    """Quantum lists it, has no text for it; the library has an OCR file that
    is not itself blank -- a blank one is nothing Quantum is withholding."""
    return by_serial(w for w in works
                     if in_quantum(w) and w.get("ocr_docx") and w.get("text") != "quantum"
                     and w["id"] not in library_blank)


def find_missed_by_batch(works):
    """In the library by the batch date, yet without an OCR file."""
    made = batch_date(works)
    if not made:
        return []
    return by_serial(w for w in works
                     if in_api(w) and w.get("added") and w["added"] <= made
                     and not w.get("ocr_docx"))


def find_hollow_texts(works):
    return by_serial(w for w in works if w.get("text") and not bytes_of(w))


def find_repeated_languages(works):
    return by_serial(w for w in works if repeats_language(w))


def find_empty_slots(works):
    counts = collections.Counter(w["classification"] for w in works if has_empty_slot(w))
    return sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))


def find_one_catalogue(works):
    return {
        "quantum": by_serial(w for w in works if in_quantum(w) and not in_api(w)),
        "api": by_serial(w for w in works if not in_quantum(w)),
    }


def library_blank_ocr(path=OCR_SIZES_PATH):
    """Library OCR files fetched and found to hold nothing past the note (034068)."""
    return {s for s, r in load_sizes(path).items() if not r.get("chars")}


def run_checks(works, empty, library_blank=frozenset()):
    return {
        "years": find_odd_years(works),
        "empty_booktexts": [(w, w["id"] in library_blank) for w in find_empty_booktexts(works, empty)],
        "unpublished_ocr": find_unpublished_ocr(works, library_blank),
        "missed_by_batch": find_missed_by_batch(works),
        "hollow": find_hollow_texts(works),
        "languages": find_repeated_languages(works),
        "slots": find_empty_slots(works),
        "one_catalogue": find_one_catalogue(works),
    }


# --- the prose figures ------------------------------------------------------


def pct(n, d):
    return round(n / d * 100) if d else None


def median(values):
    values = sorted(values)
    if not values:
        return None
    mid = len(values) // 2
    return values[mid] if len(values) % 2 else (values[mid - 1] + values[mid]) / 2


def intro_stats(tree, log, findings):
    works = sanskrit_works(tree)
    all_stats = tree.get("all_stats") or {}
    stats = {k: all_stats.get(k) for k in FROM_ALL_STATS}

    prakrit = [w for w in tree.get("works", []) if w.get("prakrit")]
    stats["prakrit_count"] = len(prakrit)
    stats["prakrit_text"] = sum(1 for w in prakrit if w.get("text"))
    stats["prakrit_canon"] = sum(1 for w in prakrit if w.get("domain") != NOT_CANON)
    stats["prakrit_undated"] = sum(1 for w in prakrit if not w.get("added"))

    text = [w for w in works if w.get("text")]
    public = [w for w in works if w.get("text") == "quantum"]
    stats["no_text"] = len(works) - len(text)
    stats["both_sources"] = sum(1 for w in works if in_quantum(w) and in_api(w))
    stats["quantum_only"] = sum(1 for w in works if in_quantum(w) and not in_api(w))
    stats["api_only"] = sum(1 for w in works if not in_quantum(w))
    stats["docx_count"] = sum(1 for w in works if w.get("ocr_docx"))

    horizontal = [w for w in works if w.get("horizontal")]
    stats["horizontal"] = len(horizontal)
    stats["horizontal_text"] = sum(1 for w in horizontal if w.get("text") == "quantum")

    stats["author_pct"] = pct(sum(1 for w in works if w.get("author")), len(works))
    # `editor` is set only where the catalogue names a classical author, the
    # catalogued author then being the modern editor.
    stats["classical_author_count"] = sum(1 for w in works if w.get("editor"))
    stats["classical_author_pct"] = pct(stats["classical_author_count"], len(works))
    stats["script_devanagari"] = sum(1 for w in works if w.get("script") == "Hindi")
    stats["classification_distinct"] = len({w.get("classification") for w in works})
    stats["canon_pct"] = pct(stats["canon_count"] or 0, len(works))

    stats["text_pages"] = sum((w.get("sizes") or {}).get("pages") or 0 for w in text)
    stats["iast_pct"] = pct(all_stats.get("transliterated_bytes") or 0,
                            all_stats.get("content_bytes") or 0)
    stats["median_bytes"] = median([bytes_of(w) for w in text])

    # Where the text stops: the newest accession with a Quantum text, the
    # newest with a library OCR file, and what came online after each.
    last_text = newest(public)
    since = [w for w in works if w.get("added") and w["added"] > last_text]
    stats["last_text_added"] = last_text[:7]
    stats["since_api_only"] = sum(1 for w in since if not in_quantum(w))
    stats["last_quantum_year"] = newest([w for w in works if in_quantum(w)])[:4]
    stats["first_api_only_year"] = min(
        (w["added"] for w in works if not in_quantum(w) and w.get("added")), default="")[:4]
    last_docx = newest([w for w in works if w.get("ocr_docx")])
    stats["last_docx_added"] = last_docx[:7]
    stats["since_text_docx"] = sum(1 for w in since if w.get("ocr_docx"))
    stats["since_last_docx"] = sum(1 for w in works if w.get("added") and w["added"] > last_docx)
    stats["docx_no_text"] = sum(1 for w in works if w.get("ocr_docx") and w.get("text") != "quantum")
    stats["ocr_created_first"] = batch_date(works)
    stats["batch_missed"] = len(findings["missed_by_batch"])
    stats["undated_text"] = sum(1 for w in works if not w.get("added") and w.get("text") == "quantum")

    periods = log.get("periods") or []
    stats["changelog_first"] = periods[0]["date"][:7] if periods else None
    stats["changelog_last"] = periods[-1]["date"][:7] if periods else None
    stats["undated_works"] = log.get("undated_works")
    stats["undated_works_prakrit"] = log.get("undated_works_prakrit")
    return stats


# --- rendering --------------------------------------------------------------
#
# Lifted from the sanskrit-documents sibling, which lifted them from
# e-bharatisampat and wikisource. Kept identical on purpose.


def _esc(s):
    return html.escape(str(s))


def _work_link(w):
    href = f"{SITE_ROOT}/explore/{w['id']}/1"
    return (f'<a href="{html.escape(href)}" target="_blank" rel="noopener">'
            f"{_esc(w.get('title_en') or w.get('title'))}</a>")


def _work_row(w, detail=""):
    return f"<code>{_esc(w['id'])}</code> {_work_link(w)}" + (f" — {detail}" if detail else "")


def _findings_list(items):
    lis = "\n".join(f"            <li>{item}</li>" for item in items)
    return f'          <ul style="margin-left: 1.6em;">\n{lis}\n          </ul>'


def _summary_text(description, label):
    # One wrapper span: `.audit-summary` is flex, and flex discards the
    # whitespace between items.
    return f"<span>{description} ({label})</span>"


def _bullet(description, count, inner_html, unit=None):
    """One finding. A zero still renders, as "none found": silence and success
    must not look the same."""
    if count == 0:
        return (f'          <li class="audit-item"><div class="audit-summary '
                f'audit-summary-empty"><span>{description}: none found</span></div></li>')
    label = unit if unit is not None else f"{count:,}"
    return (
        f'          <li class="audit-item"><details>\n'
        f'            <summary class="audit-summary">{_summary_text(description, label)}</summary>\n'
        f"{inner_html}\n"
        f"          </details></li>"
    )


def _sub_bullet(description, count, inner_html):
    return (
        f'<li class="audit-item"><details>\n'
        f'<summary class="audit-summary">{_summary_text(description, f"{count:,}")}</summary>\n'
        f"{inner_html}\n"
        f"</details></li>"
    )


def _group_ul(items):
    return ('          <ul style="margin-left: 1.6em; list-style: none; padding-left: 0;">\n'
            + "\n".join(f"            {item}" for item in items)
            + "\n          </ul>")


def _preamble(text_html):
    """The one sentence between a finding's summary and its items."""
    return f'          <p style="margin-left: 1.6em;">{text_html}</p>'


def _capped(items):
    if len(items) <= MAX_EXAMPLES:
        return items
    return items[:MAX_EXAMPLES] + [f"<em>… and {len(items) - MAX_EXAMPLES:,} more</em>"]


def _items(n):
    return f"{n:,} {'item' if n == 1 else 'items'}"


def _online(w):
    return f"online {w['added']}" if w.get("added") else ""


def render_years(rows):
    inner = (_preamble("The catalogued year is not a four-digit year between 1700 and the present.")
             + "\n" + _findings_list(_capped([_work_row(w, f'"{_esc(w["publish_year"])}"') for w in rows])))
    return _bullet("Publication years that cannot be right", len(rows), inner, unit=_items(len(rows)))


def render_empty_booktexts(pairs):
    rows = [w for w, _ in pairs]
    blank = {w["id"] for w, b in pairs if b}

    def detail(w):
        if w.get("text") == "elibrary":
            return "the library's OCR has text"
        if w["id"] in blank:
            return "the library's OCR file is blank too"
        return "the library has an OCR file" if w.get("ocr_docx") else "no OCR anywhere"

    inner = (_preamble("Jain Quantum serves a text page for each, with page markers but nothing on "
                       "the pages. Where the library's own OCR has text, the Atlas uses that instead.")
             + "\n" + _findings_list(_capped([_work_row(w, detail(w)) for w in rows])))
    return _bullet("Text pages on Jain Quantum that are empty", len(rows), inner, unit=_items(len(rows)))


def render_unpublished_ocr(rows):
    groups = []
    for year, n in by_year(rows):
        members = [w for w in rows if ((w.get("added") or "")[:4] or "undated") == year]
        groups.append(_sub_bullet(_esc(year), n, _findings_list([_work_row(w, _online(w)) for w in members])))
    inner = (_preamble("Jain Quantum lists these with no text to read or search, though the library "
                       "OCR'd each one; its Word file is downloadable only with an account. "
                       "By the year the book went online.")
             + "\n" + _group_ul(groups))
    return _bullet("OCR the library has but Jain Quantum does not show", len(rows), inner,
                   unit=_items(len(rows)))


def render_missed_by_batch(rows, made):
    inner = (_preamble(f"The library's OCR files were all made on {_esc(made)}, over the books then "
                       "online; these were online by that day but have no OCR file.")
             + "\n" + _findings_list([_work_row(w, _online(w)) for w in rows]))
    return _bullet("Books the library's OCR batch skipped", len(rows), inner, unit=_items(len(rows)))


def render_languages(rows):
    inner = _findings_list(_capped([_work_row(w, f'"{_esc(w["language"])}"') for w in rows]))
    return _bullet("Language strings that repeat themselves", len(rows), inner, unit=_items(len(rows)))


def render_slots(rows):
    total = sum(n for _, n in rows)
    inner = (_preamble("The classification is a comma-separated list, and these have nothing between "
                       "two of their commas or after the last. Items carrying each string in parentheses.")
             + "\n" + _findings_list([f"<code>{_esc(s)}</code> ({n:,})" for s, n in rows]))
    return _bullet("Classification strings with empty slots", total, inner,
                   unit=f"{_items(total)}, {len(rows)} distinct strings")


def render_one_catalogue(groups):
    quantum, api = groups["quantum"], groups["api"]

    def q_detail(w):
        return "text on Quantum" if w.get("text") == "quantum" else "no text anywhere"

    subs = [
        _sub_bullet("Jain Quantum only", len(quantum),
                    _findings_list(_capped([_work_row(w, q_detail(w)) for w in quantum]))),
        _sub_bullet("jainelibrary.org only", len(api),
                    _findings_list(_capped([_work_row(w, _online(w)) for w in api]))),
    ]
    inner = (_preamble("Both sites present the same library under the same serials, but neither lists "
                       "all of it. A book only Jain Quantum lists has no accession date and no OCR file, "
                       "both of which come from the library; one only jainelibrary.org lists has no "
                       "public text.")
             + "\n" + _group_ul(subs))
    n = len(quantum) + len(api)
    return _bullet("Items in only one of the two catalogues", n, inner, unit=_items(n))


def render_audit_html(findings, made):
    rows = [
        render_years(findings["years"]),
        render_empty_booktexts(findings["empty_booktexts"]),
        render_unpublished_ocr(findings["unpublished_ocr"]),
        render_missed_by_batch(findings["missed_by_batch"], made),
        render_languages(findings["languages"]),
        render_slots(findings["slots"]),
        render_one_catalogue(findings["one_catalogue"]),
    ]
    return (
        '        <h3 id="opportunities-for-correction">Opportunities for Correction</h3>\n'
        "        <p>\n"
        "          The Atlas codebase also includes an audit pipeline for\n"
        "          detecting and concisely indicating problems that should be fixed on\n"
        "          jainelibrary.org or Jain Quantum. It covers the Sanskrit books only,\n"
        "          and every figure below is re-derived by the run that publishes it.\n"
        "        </p>\n"
        '        <ul style="list-style: none; padding-left: 0;">\n'
        + "\n".join(rows)
        + "\n        </ul>"
    )


# --- writing back -----------------------------------------------------------


def update_about_html(new_html, path=ABOUT_HTML_PATH):
    """Replace the block between the AUDIT markers: a string splice, not a parse."""
    text = path.read_text(encoding="utf-8")
    try:
        start = text.index(AUDIT_START_MARKER) + len(AUDIT_START_MARKER)
        end = text.index(AUDIT_END_MARKER)
    except ValueError as err:
        raise SystemExit(f"{path} has no AUDIT:START/AUDIT:END markers") from err
    path.write_text(text[:start] + "\n" + new_html + "\n        " + text[end:], encoding="utf-8")


# `data-unit` scales a byte figure where the prose reads it in MB or KB.
UNITS = {"mb": 1e6, "kb": 1e3}


def _fmt(value, unit=None):
    """Integers and scaled bytes get thousands separators; strings pass
    through. An absent figure publishes as an em dash, never a zero."""
    if value is None or value == "":
        return "—"
    if isinstance(value, str):
        return value
    if unit:
        return f"{value / UNITS[unit]:,.0f}"
    if isinstance(value, int):
        return f"{value:,}"
    return f"{value:,.1f}"


def update_intro_stats(stats, path=ABOUT_HTML_PATH):
    """Rewrite each `data-stat` figure in the prose, strict in both directions:
    a tag naming a figure the audit does not compute, or a computed figure
    with no tag, is an error -- a stale published number is the failure this
    replaces."""
    text = path.read_text(encoding="utf-8")
    seen = set()
    pattern = re.compile(
        r'(?P<open><(?P<tag>span|text)\b[^>]*\bdata-stat="(?P<key>[^"]+)"[^>]*>)'
        r"[^<]*"
        r"(?P<close></(?P=tag)>)"
    )

    def sub(match):
        key = match.group("key")
        if key not in stats:
            raise SystemExit(f'{path} tags data-stat="{key}", which the audit does not compute')
        seen.add(key)
        unit = re.search(r'\bdata-unit="(\w+)"', match.group("open"))
        return f"{match.group('open')}{_fmt(stats[key], unit and unit.group(1))}{match.group('close')}"

    updated = pattern.sub(sub, text)
    # Write before checking the reverse direction: `updated` is already right
    # for every tag present, and the check is about the next edit.
    path.write_text(updated, encoding="utf-8")
    missing = sorted(set(stats) - seen)
    if missing:
        raise SystemExit(f"{path} has no data-stat tag for: {', '.join(missing)} -- "
                         f"tag the figure in the prose or drop it from intro_stats()")
    return len(seen)


# --- report -----------------------------------------------------------------


def print_report(findings, works):
    print(f"audit of {len(works):,} Sanskrit books ({date.today().isoformat()})\n")
    one = findings["one_catalogue"]
    rows = [
        ("publication years that cannot be right", len(findings["years"])),
        ("empty Quantum text pages", len(findings["empty_booktexts"])),
        ("library OCR that Quantum does not show", len(findings["unpublished_ocr"])),
        ("skipped by the library's OCR batch", len(findings["missed_by_batch"])),
        ("ours: counted texts holding nothing", len(findings["hollow"])),
        ("repeated language strings", len(findings["languages"])),
        ("classifications with empty slots", sum(n for _, n in findings["slots"])),
        ("on Jain Quantum only", len(one["quantum"])),
        ("on jainelibrary.org only", len(one["api"])),
    ]
    for label, count in rows:
        print(f"  {count:>6,}  {label}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--update-about", action="store_true",
                        help="rewrite the AUDIT region and the data-stat figures in docs/about.html")
    args = parser.parse_args()

    tree = load_tree()
    log = load_changelog()
    works = sanskrit_works(tree)
    findings = run_checks(works, empty_booktexts(TEXT_LOG_PATH, load_sizes(SIZES_PATH)),
                          library_blank_ocr())
    stats = intro_stats(tree, log, findings)
    print_report(findings, works)

    if args.update_about:
        update_about_html(render_audit_html(findings, batch_date(works)))
        print(f"\nwrote the audit region of {ABOUT_HTML_PATH}")
        print(f"refreshed {update_intro_stats(stats)} figures in the same file")


if __name__ == "__main__":
    main()
